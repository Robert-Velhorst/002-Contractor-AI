const { test, expect } = require('@playwright/test');
const AxeBuilder = require('@axe-core/playwright').default;

test('office builds a shared work dossier and the assigned phone work pack retains it offline', async ({ page, request, browser }, testInfo) => {
  const base = `http://127.0.0.1:${process.env.CONTRACTOR_AI_BROWSER_AUTH_PORT}`;
  const owner = { Authorization: 'Bearer browser-owner-token-at-least-32-characters' };
  const workerId = 'browser-field-task-worker', title = `Work context ${Date.now()}`;
  expect((await request.post(`${base}/api/ledger/workers`, { headers: owner, data: { id: workerId, name: 'Context worker', role: 'Carpenter', status: 'available' } })).ok()).toBeTruthy();
  const intake = await request.post(`${base}/api/ledger/intake`, { headers: owner, data: { title, client: { name: 'Context customer' }, tasks: [{ title: 'Montage deuren', assigneeId: workerId }], assignAutomatically: false } });
  expect(intake.ok()).toBeTruthy(); const { job } = await intake.json();
  expect((await request.post(`${base}/api/ledger/jobs/${job.id}/assignments`, { headers: owner, data: { workerId, status: 'assigned', role: 'Carpenter' } })).ok()).toBeTruthy();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 }); await page.goto(base);
  await page.locator('#operator-access-key').fill('browser-owner-token-at-least-32-characters');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByLabel(/^(Language|Taal)$/).selectOption('en-GB');
  await page.getByRole('button', { name: `Open ${title}`, exact: true }).first().click();
  const panel = page.getByRole('region', { name: 'Werkdossier', exact: true });
  await panel.getByRole('button', { name: 'Locatie toevoegen', exact: true }).click();
  await panel.getByLabel('Locatienaam', { exact: true }).fill('Werkstraat 10');
  await panel.getByLabel('Locatieadres / aanduiding').fill('Arnhem');
  await panel.getByRole('button', { name: 'Opslaan', exact: true }).click();
  await expect(panel.getByText('Werkstraat 10', { exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Werkpakket toevoegen', exact: true }).click();
  await panel.getByLabel('Werkpakketcode', { exact: true }).fill('WP-01');
  await panel.getByLabel('Werkpakketnaam', { exact: true }).fill('Deurmontage');
  await panel.getByRole('combobox', { name: 'Werklocatie', exact: true }).selectOption({ label: 'Werkstraat 10' });
  await panel.getByLabel('Beoogd resultaat').fill('Twee passende deuren');
  await panel.getByLabel('Veilig stoppunt bij onderbreking').fill('Opening afzetten');
  await panel.getByLabel('Benodigde overdracht').fill('Foto en maat doorgeven');
  await panel.getByLabel('Montage deuren', { exact: true }).check();
  await panel.getByRole('button', { name: 'Opslaan', exact: true }).click();
  await expect(panel.getByText('WP-01 / Deurmontage', { exact: true })).toBeVisible();
  const board = page.getByRole('region', { name: 'Open posities', exact: true });
  await board.getByText('Positie vrijgeven', { exact: true }).first().click();
  await expect(board.getByRole('combobox', { name: 'Werkpakket', exact: true }).getByRole('option', { name: 'WP-01 / Deurmontage', exact: true })).toBeAttached();
  await panel.getByRole('button', { name: 'Betrokkene toevoegen' }).click();
  await panel.getByLabel('Naam betrokkene').fill('Private betaler');
  await panel.getByLabel('E-mail', { exact: true }).fill('private-payer@example.test');
  await panel.getByLabel('Betaler', { exact: true }).check();
  await panel.getByLabel('Bron of afstemming over deze rol').fill('Schriftelijke afspraak');
  await panel.getByRole('button', { name: 'Opslaan', exact: true }).click();
  await expect(panel.getByText('Private betaler', { exact: true })).toBeVisible();
  const exported = page.waitForEvent('download'); await panel.getByRole('button', { name: 'Werkdossier exporteren' }).click();
  expect((await exported).suggestedFilename()).toBe(`werkdossier-${job.id}.json`);
  await panel.scrollIntoViewIfNeeded(); await page.screenshot({ path: testInfo.outputPath('work-context-desktop.png') });
  expect((await new AxeBuilder({ page }).include('.work-context').analyze()).violations).toEqual([]);
  await panel.getByRole('button', { name: 'Archiveren Private betaler' }).click();
  await expect(panel.getByRole('button', { name: 'Herstellen Private betaler' })).toBeVisible();
  await panel.getByRole('button', { name: 'Herstellen Private betaler' }).click();
  await expect(panel.getByRole('button', { name: 'Archiveren Private betaler' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.getByRole('button', { name: 'Deurmontage: bewerken' }).click();
  await expect(panel.getByLabel('Beoogd resultaat')).toHaveValue('Twee passende deuren');
  expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await panel.locator('.context-editor').scrollIntoViewIfNeeded(); await page.screenshot({ path: testInfo.outputPath('work-context-mobile.png') });
  expect((await new AxeBuilder({ page }).include('.work-context').analyze()).violations).toEqual([]);
  const phoneContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  try {
    const phone = await phoneContext.newPage(); phone.on('pageerror', error => errors.push(error.message));
    await phone.goto(base); await phone.locator('#operator-access-key').fill('browser-field-token-at-least-32-characters');
    await phone.getByRole('button', { name: 'Sign in', exact: true }).click();
    await phone.getByLabel(/^(Language|Taal)$/).selectOption('nl-NL');
    const pack = phone.getByTestId('field-work-pack');
    await pack.getByRole('button', { name: `Werkpakket ${title} openen` }).click();
    await pack.getByRole('tab', { name: 'Weten', exact: true }).click();
    await expect(pack.getByText('Opening afzetten', { exact: true })).toBeVisible();
    await expect(pack.getByText('Private betaler')).toHaveCount(0);
    expect(await pack.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
    await phone.screenshot({ path: testInfo.outputPath('work-context-field.png') });
    expect((await new AxeBuilder({ page: phone }).include('[data-testid="field-work-pack"]').analyze()).violations).toEqual([]);
    await pack.getByText('Offline werkmap', { exact: true }).click();
    await pack.getByLabel('Offline wachtzin (minimaal 10 tekens)').fill('work-context-offline-passphrase');
    await pack.getByRole('button', { name: 'Werkpakket offline bewaren' }).click();
    await expect(pack.getByText('Versleuteld opgeslagen voor maximaal 7 dagen.')).toBeVisible();
    await phone.goto(`${base}/field-offline.html`);
    await phoneContext.setOffline(true);
    await phone.reload();
    await phone.getByLabel('Offline wachtzin', { exact: true }).fill('work-context-offline-passphrase');
    await phone.getByRole('button', { name: 'Ontgrendelen', exact: true }).click();
    await phone.getByRole('button', { name: 'Weten', exact: true }).click();
    await expect(phone.getByText('Opening afzetten', { exact: true })).toBeVisible();
    await expect(phone.getByText('private-payer@example.test')).toHaveCount(0);
    await phone.screenshot({ path: testInfo.outputPath('work-context-offline.png') });
    const read = await request.get(`${base}/api/ledger/jobs/${job.id}/work-pack?workerId=${workerId}`, { headers: owner });
    const payload = (await read.json()).pack;
    expect(payload.know.workContext.packages[0].stopPoint).toBe('Opening afzetten');
    expect(JSON.stringify(payload)).not.toContain('private-payer@example.test');
  } finally { await phoneContext.close(); }
  expect(errors).toEqual([]);
});
