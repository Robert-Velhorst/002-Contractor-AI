const { test, expect } = require('@playwright/test');
const AxeBuilder = require('@axe-core/playwright').default;

test('office retains a partial delivery, verifies a separate client response and shares only execution with the offline phone', async ({ page, request, browser }, testInfo) => {
  const base = `http://127.0.0.1:${process.env.CONTRACTOR_AI_BROWSER_AUTH_PORT}`;
  const owner = { Authorization: 'Bearer browser-owner-token-at-least-32-characters' };
  async function post(route, data) {
    const result = await request.post(base + route, { headers: owner, data });
    expect(result.ok(), await result.text()).toBeTruthy(); return result.json();
  }
  async function get(route) { const result = await request.get(base + route, { headers: owner }); expect(result.ok()).toBeTruthy(); return result.json(); }
  const workerId = 'browser-field-task-worker', title = `Partial delivery ${Date.now()}`;
  await post('/api/ledger/workers', { id: workerId, name: 'Delivery worker', role: 'Carpenter', status: 'available' });
  const { job } = await post('/api/ledger/intake', { title, client: { name: 'Delivery customer' }, tasks: [{ title: 'Montage deuren', assigneeId: workerId }], assignAutomatically: false });
  await post(`/api/ledger/jobs/${job.id}/assignments`, { workerId, status: 'assigned', role: 'Carpenter' });
  const context = await get(`/api/ledger/jobs/${job.id}/work-context`);
  await post(`/api/ledger/jobs/${job.id}/work-context`, { action: 'save_package', sourceHash: context.sourceHash, entryKey: 'delivery-package', record: { code: 'WP-01', title: 'Deurmontage', outcome: 'Twee deuren plaatsen', taskIds: [job.tasks[0].id], quantityIds: [] } });
  const baseline = await post(`/api/ledger/jobs/${job.id}/production-baselines`, { lines: [{ lineKey: 'doors', costCode: 'DOORS', description: 'Deuren', unit: 'st', plannedQuantity: 2, plannedLaborHours: 8 }] });
  await post(`/api/ledger/approvals/${baseline.approval.id}/resolve?includeDashboard=false`, { status: 'approved' });
  await post(`/api/ledger/jobs/${job.id}/production-entries`, { lineKey: 'doors', workDate: '2026-09-01', quantity: 1, crewHours: 4, note: 'Eerste deur gemonteerd', entryKey: 'delivery-browser-entry' });
  await post(`/api/ledger/jobs/${job.id}/documents`, { title: 'Getekende deeloplevering', type: 'acceptance_evidence', status: 'retained', data: { reference: 'Synthetic retained field acceptance record' } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 }); await page.goto(base);
  await page.locator('#operator-access-key').fill('browser-owner-token-at-least-32-characters');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByLabel(/^(Language|Taal)$/).selectOption('en-GB');
  await page.getByRole('button', { name: `Open ${title}`, exact: true }).first().click();
  const panel = page.getByRole('region', { name: 'Deelopleveringen', exact: true });
  const workContext = page.getByRole('region', { name: 'Werkdossier', exact: true });
  await workContext.getByRole('button', { name: 'Locatie toevoegen', exact: true }).click();
  await workContext.getByLabel('Locatienaam', { exact: true }).fill('Bewaarde andere invoer');
  await panel.getByRole('button', { name: 'Uitgevoerd deel vastleggen' }).click();
  await panel.getByRole('combobox', { name: 'Werkpakket', exact: true }).selectOption({ label: 'WP-01 / Deurmontage' });
  await panel.getByLabel('Titel deeloplevering').fill('Eerste deur opgeleverd');
  await panel.getByLabel('Uitgevoerd deel en resterend werk').fill('Eerste deur geplaatst. Tweede deur nog uitvoeren.');
  await panel.getByRole('checkbox', { name: /doors: 1 st/ }).check();
  await panel.getByRole('button', { name: 'Opslaan', exact: true }).click();
  await expect(panel.getByText('Uitvoering gemeld', { exact: true })).toBeVisible();
  await expect(panel.getByText('Niet geverifieerd', { exact: true })).toBeVisible();
  await expect(workContext.getByLabel('Locatienaam', { exact: true })).toHaveValue('Bewaarde andere invoer');
  await workContext.getByRole('button', { name: 'Annuleren', exact: true }).click();
  await panel.getByRole('button', { name: 'Klantreactie ter beoordeling' }).click();
  await panel.getByLabel('Naam klant / vertegenwoordiger').fill('Private customer name');
  await panel.getByLabel('Datum klantreactie').fill('2026-09-01');
  await panel.getByLabel('Onderbouwing bevoegdheid').fill('Private signed authority');
  await panel.getByRole('combobox', { name: 'Klantbewijs' }).selectOption({ label: 'Getekende deeloplevering' });
  await panel.getByLabel('Toelichting / voorbehoud').fill('Alleen de eerste deur wordt geaccepteerd.');
  await panel.getByRole('button', { name: 'Ter beoordeling indienen' }).click();
  await expect(panel.getByText('Beoordeling openstaand')).toBeVisible();
  const pending = (await get(`/api/ledger/jobs/${job.id}/work-deliveries`)).records[0].decisions[0];
  await post(`/api/ledger/approvals/${pending.approvalId}/resolve?includeDashboard=false`, { status: 'approved' });
  await panel.getByRole('button', { name: 'Deelopleveringen verversen' }).click();
  await expect(panel.getByText('Geaccepteerd', { exact: true })).toBeVisible();
  await expect(panel.getByText('Geen keuring gekoppeld')).toBeVisible();
  await expect(panel.getByText('Geen termijn gekoppeld')).toBeVisible();
  const download = page.waitForEvent('download'); await panel.getByRole('button', { name: 'Deelopleveringen exporteren' }).click();
  expect((await download).suggestedFilename()).toBe(`deelopleveringen-${job.id}.json`);
  await panel.scrollIntoViewIfNeeded(); await page.screenshot({ path: testInfo.outputPath('delivery-desktop.png') });
  expect((await new AxeBuilder({ page }).include('.work-delivery').analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 }); await panel.scrollIntoViewIfNeeded();
  expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('delivery-mobile.png') });
  expect((await new AxeBuilder({ page }).include('.work-delivery').analyze()).violations).toEqual([]);
  const phoneContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  try {
    const phone = await phoneContext.newPage(); phone.on('pageerror', error => errors.push(error.message));
    await phone.goto(base); await phone.locator('#operator-access-key').fill('browser-field-token-at-least-32-characters');
    await phone.getByRole('button', { name: 'Sign in', exact: true }).click();
    await phone.getByLabel(/^(Language|Taal)$/).selectOption('nl-NL');
    const pack = phone.getByTestId('field-work-pack');
    await pack.getByRole('button', { name: `Open werkpakket ${title}` }).click();
    await pack.getByRole('tab', { name: 'Weten', exact: true }).click();
    await expect(pack.getByText('Eerste deur opgeleverd', { exact: true })).toBeVisible();
    await expect(pack.getByText('Private customer name')).toHaveCount(0);
    await pack.getByText('Offline werkmap', { exact: true }).click();
    await pack.getByLabel('Offline wachtzin (minimaal 10 tekens)').fill('work-delivery-offline-passphrase');
    await pack.getByRole('button', { name: 'Werkpakket offline bewaren' }).click();
    await expect(pack.getByText('Versleuteld opgeslagen voor maximaal 7 dagen.')).toBeVisible();
    await phone.goto(`${base}/field-offline.html`); await phoneContext.setOffline(true); await phone.reload();
    await phone.getByLabel('Offline wachtzin', { exact: true }).fill('work-delivery-offline-passphrase');
    await phone.getByRole('button', { name: 'Ontgrendelen', exact: true }).click();
    await phone.getByRole('button', { name: 'Weten', exact: true }).click();
    await expect(phone.getByText('Eerste deur opgeleverd', { exact: true })).toBeVisible();
    await expect(phone.getByText('Private customer name')).toHaveCount(0);
    await phone.screenshot({ path: testInfo.outputPath('delivery-offline.png') });
  } finally { await phoneContext.close(); }
  expect(errors).toEqual([]);
});
