const { test, expect } = require('@playwright/test');
const { identityFixture } = require('../tests/identity-fixture');
const { expectNoAxeViolations } = require('./accessibility-helpers');

test('personal registration, company invitation, reviewed worker admission, SSO and recovery work through real controls', async ({ browser }, testInfo) => {
  test.setTimeout(180000);
  const cleanups = [];
  const fixture = await identityFixture({ after: cleanup => cleanups.push(cleanup) });
  const ownerContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const workerContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const owner = await ownerContext.newPage(), worker = await workerContext.newPage(), errors = [];
  ownerContext.setDefaultTimeout(15000); workerContext.setDefaultTimeout(15000);
  owner.on('pageerror', error => errors.push(error.message)); worker.on('pageerror', error => errors.push(error.message));
  try {
    const a = fixture.runtimes[0];
    await owner.goto(a.origin);
    await expect(owner.getByRole('link', { name: 'Inloggen met persoonlijk account' })).toBeVisible();
    await owner.getByLabel('Access key', { exact: true }).fill(a.ownerKey);
    await owner.getByRole('button', { name: 'Sign in', exact: true }).click();
    await owner.getByLabel(/^(Language|Taal)$/).selectOption('nl-NL');
    await owner.getByRole('button', { name: 'Beheer', exact: true }).click();
    const access = owner.getByRole('region', { name: 'Bedrijfstoegang', exact: true });
    await expect(access.getByText('Company alpha', { exact: true })).toBeVisible();
    await access.locator('summary').filter({ hasText: 'Nieuwe bedrijfsuitnodiging' }).click();
    await access.getByLabel('Uitvoerdersprofiel', { exact: true }).selectOption(a.worker.id);
    await access.getByLabel('Referentie uitnodigingscontrole').fill('Browser fixture: contact and worker profile reviewed');
    await access.getByRole('button', { name: 'Uitnodiging aanmaken', exact: true }).click();
    const inviteInput = access.getByLabel('Persoonlijke uitnodigingslink (eenmalig zichtbaar)');
    await expect(inviteInput).toBeVisible();
    await worker.goto(await inviteInput.inputValue());
    await expect(worker.getByRole('heading', { name: 'Uitnodiging van Company alpha' })).toBeVisible();
    expect(new URL(worker.url()).hash).toBe('');
    await worker.getByRole('button', { name: 'Registreren', exact: true }).click();
    await worker.getByLabel('Naam', { exact: true }).fill('Identity test worker');
    await worker.getByLabel('Gebruikersnaam', { exact: true }).fill('identity-browser-worker');
    await worker.getByLabel('Wachtwoord', { exact: true }).fill('a long unique browser password');
    await worker.getByLabel('Herhaal wachtwoord', { exact: true }).fill('a long unique browser password');
    await worker.getByRole('checkbox').check();
    await worker.getByRole('button', { name: 'Account aanmaken', exact: true }).click();
    await expect(worker.getByRole('heading', { name: 'Persoonlijke herstelcodes' })).toBeVisible();
    const recoveryCode = await worker.locator('.identity-recovery code').first().innerText();
    const download = worker.waitForEvent('download');
    await worker.getByRole('button', { name: 'Herstelcodes downloaden', exact: true }).click();
    expect((await download).suggestedFilename()).toBe('contractor-herstelcodes.txt');
    await worker.getByRole('button', { name: 'Veilig bewaard', exact: true }).click();
    await worker.getByLabel('Wachtwoord', { exact: true }).fill('a long unique browser password');
    await worker.locator('form').getByRole('button', { name: 'Inloggen', exact: true }).click();
    await worker.getByRole('button', { name: 'Uitnodiging accepteren', exact: true }).click();
    await expect(worker.getByText('Uitvoerende | Wacht op beoordeling', { exact: true })).toBeVisible();
    await expectNoAxeViolations(worker, 'mobile identity account and pending membership');
    await worker.screenshot({ path: testInfo.outputPath('identity-mobile-pending.png'), fullPage: true });
    await access.getByRole('button', { name: 'Bedrijfstoegang verversen' }).click();
    const membership = access.locator('article').filter({ hasText: 'Identity test worker' });
    await membership.locator('summary').click();
    await membership.getByLabel('Referentie identiteits- en toelatingscontrole').fill('Browser fixture: identity verified independently');
    await membership.getByRole('button', { name: 'Besluit vastleggen' }).click();
    await expect(membership.getByText('identity-browser-worker | Uitvoerende | Toegelaten', { exact: true })).toBeVisible();
    await access.getByRole('button', { name: 'Uitnodigingslink verbergen' }).click();
    await access.screenshot({ path: testInfo.outputPath('identity-office-admission.png') });
    await worker.getByRole('button', { name: 'Bedrijven verversen' }).click();
    await worker.getByRole('link', { name: 'Open Company alpha' }).click();
    await worker.getByRole('button', { name: 'Verder naar bedrijf', exact: true }).click();
    await worker.getByRole('button', { name: 'Toegang bevestigen', exact: true }).click();
    await expect(worker).toHaveURL(`${a.origin}/work-board.html`);
    await expect(worker.getByRole('heading', { name: 'Beschikbaar werk' })).toBeVisible();
    await expect(worker.getByText('Worker alpha | Toegelaten', { exact: true })).toBeVisible();
    expect(await worker.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await expectNoAxeViolations(worker, 'mobile work board authenticated by shared identity');
    await worker.screenshot({ path: testInfo.outputPath('identity-worker-board.png'), fullPage: true });
    await worker.getByRole('button', { name: 'Uitloggen', exact: true }).click();
    await expect(worker.getByRole('heading', { name: 'Inloggen', exact: true })).toBeVisible();
    await worker.getByRole('link', { name: 'Mijn account en bedrijven' }).click();
    await worker.getByRole('button', { name: 'Uitloggen uit accountomgeving' }).click();
    await worker.getByRole('button', { name: 'Herstellen', exact: true }).click();
    await worker.getByLabel('Gebruikersnaam', { exact: true }).fill('identity-browser-worker');
    await worker.getByLabel('Eenmalige herstelcode').fill(recoveryCode);
    await worker.getByLabel('Nieuw wachtwoord', { exact: true }).fill('a new recovered browser password');
    await worker.getByLabel('Herhaal wachtwoord', { exact: true }).fill('a new recovered browser password');
    await worker.getByRole('button', { name: 'Wachtwoord herstellen', exact: true }).click();
    await expect(worker.getByRole('status')).toContainText('Wachtwoord hersteld');
    const person = fixture.registry.db.prepare('SELECT id FROM registry_identities WHERE login_name = ?').get('identity-browser-worker');
    const assisted = fixture.registry.issueAssistedRecovery(person.id, { expectedLoginName: 'identity-browser-worker',
      reference: 'Browser fixture independent identity review', deliveryReference: 'Browser fixture private delivery',
      confirmation: 'AUTHORIZE_PERSON_RECOVERY' }, 'fixture-registry-operator');
    await worker.getByRole('button', { name: 'Herstellen', exact: true }).click();
    await worker.getByLabel('Eenmalige herstelcode').fill(assisted.recoveryCode);
    await worker.getByLabel('Nieuw wachtwoord', { exact: true }).fill('assisted verified browser password');
    await worker.getByLabel('Herhaal wachtwoord', { exact: true }).fill('assisted verified browser password');
    await worker.getByRole('button', { name: 'Wachtwoord herstellen', exact: true }).click();
    await expect(worker.getByRole('heading', { name: 'Persoonlijke herstelcodes' })).toBeVisible();
    await expect(worker.locator('.identity-recovery code')).toHaveCount(8);
    await expectNoAxeViolations(worker, 'assisted account recovery with fresh one-use codes');
    await worker.getByRole('button', { name: 'Veilig bewaard', exact: true }).click();
    await expect(worker.getByRole('heading', { name: 'Persoonlijke herstelcodes' })).toHaveCount(0);
    await worker.getByLabel('Wachtwoord', { exact: true }).fill('assisted verified browser password');
    await worker.locator('form').getByRole('button', { name: 'Inloggen', exact: true }).click();
    await expect(worker.getByRole('link', { name: 'Open Company alpha' })).toBeVisible();
    expect(errors).toEqual([]);
  } finally {
    await workerContext.close().catch(() => {}); await ownerContext.close().catch(() => {});
    for (const cleanup of cleanups.reverse()) await cleanup();
  }
});
