const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { ContractorOperatingLedger } = require('../operating-ledger');
const { setupAssetHistory } = require('./asset-history-contract');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'asset-history-api-'));
Object.assign(process.env, { STATE_FILE: path.join(directory, 'state.json'), LEDGER_DB_FILE: path.join(directory, 'ledger.sqlite'), UPLOAD_DIR: path.join(directory, 'uploads'), CONTRACTOR_AI_REQUIRE_AUTH: 'true' });
const tokens = { owner: 'asset-history-owner-token-at-least-32-characters', office_operator: 'asset-history-office-token-at-least-32-characters', approver: 'asset-history-approver-token-at-least-32-characters' };
const ledger = new ContractorOperatingLedger({ dbFile: process.env.LEDGER_DB_FILE });
const f = setupAssetHistory(ledger);
tokens.field_worker = { token: 'asset-history-field-token-at-least-32-characters', workerId: f.worker.id };
process.env.CONTRACTOR_AI_ROLE_TOKENS = JSON.stringify(tokens);
const document = ledger.addDocument(f.job.id, { title: 'Private installed asset evidence', type: 'asset_history_evidence', data: { reference: 'Private office archive reference' } });
const fixture = { jobId: f.job.id, otherId: f.other.id, input: f.input, assetId: f.asset.id, documentId: document.id };
ledger.close();
const app = require('../server');

test('asset APIs enforce office writes, private evidence and operational-only field projection', async t => {
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await app.locals.runtimeControl.shutdown({ server, signal: 'asset_history_api_test' }); assert.ok(path.basename(directory).startsWith('asset-history-api-')); fs.rmSync(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`, route = `/api/ledger/jobs/${fixture.jobId}/asset-history`;
  async function request(route, token, data) {
    const response = await fetch(base + route, { method: data ? 'POST' : 'GET', headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), 'Content-Type': 'application/json' }, ...(data ? { body: JSON.stringify(data) } : {}) });
    return { status: response.status, body: await response.json() };
  }
  assert.equal((await request(route)).status, 401);
  assert.equal((await request(route, tokens.field_worker.token)).status, 403);
  assert.equal((await request(`/api/ledger/documents/${fixture.documentId}/content`, tokens.field_worker.token)).status, 403);
  const source = (await request(route, tokens.approver)).body;
  const input = { action: 'record', record: fixture.input, sourceHash: source.sourceHash, entryKey: 'asset-api-record', actor: 'spoofed' };
  assert.equal((await request(route, tokens.approver, input)).status, 403);
  const created = await request(route, tokens.office_operator, input);
  assert.equal(created.status, 201);
  assert.equal((await request(route, tokens.office_operator, input)).body.replayed, true);
  assert.equal((await request(route, tokens.office_operator, { ...input, entryKey: 'stale' })).status, 409);
  const current = (await request(route, tokens.owner)).body;
  assert.equal((await request(route, tokens.office_operator, { action: 'share', record: { assetId: fixture.assetId, id: created.body.eventIds[0], enabled: true, fieldSummary: 'Filter gecontroleerd' }, sourceHash: current.sourceHash, entryKey: 'api-share' })).status, 201);
  const field = (await request(`/api/ledger/jobs/${fixture.jobId}/work-pack`, tokens.field_worker.token)).body.pack;
  assert.equal(field.know.workContext.installedAssets[0].events[0].summary, 'Filter gecontroleerd');
  for (const value of ['Private office', 'Private installed', fixture.documentId]) assert.equal(JSON.stringify(field).includes(value), false);
  const job = (await request(`/api/ledger/jobs/${fixture.jobId}`, tokens.field_worker.token)).body.job;
  assert.equal(job.documents.some(row => row.id === fixture.documentId), false);
  assert.equal((await request(`/api/ledger/jobs/${fixture.otherId}/work-pack`, tokens.field_worker.token)).status, 403);
  const exported = (await request('/api/operations/export', tokens.owner)).body;
  assert.equal(exported.installedAssets.asset_service_events.length, 1);
  const officeJob = (await request(`/api/ledger/jobs/${fixture.jobId}`, tokens.owner)).body.job;
  assert.equal(officeJob.audit.some(row => row.action === 'asset_history_record' && row.actor === 'spoofed'), false);
  for (const approval of officeJob.approvals.filter(row => row.status === 'pending')) assert.equal((await request(`/api/ledger/approvals/${approval.id}/resolve?includeDashboard=false`, tokens.owner, { status: 'rejected', reason: 'Fixture preparation withdrawn before archive' })).status, 200);
  const archive = await request(`/api/ledger/jobs/${fixture.jobId}/archive`, tokens.owner, { reason: 'Retained completed source dossier' });
  assert.equal(archive.status, 201, JSON.stringify(archive.body));
  assert.equal((await request(`/api/ledger/approvals/${archive.body.approval.id}/resolve?includeDashboard=false`, tokens.owner, { status: 'approved' })).status, 200);
  const archived = (await request(route, tokens.owner)).body;
  const withdrawn = await request(route, tokens.office_operator, { action: 'share', record: { assetId: fixture.assetId, id: created.body.eventIds[0], enabled: false }, sourceHash: archived.sourceHash, entryKey: 'withdraw-archived' });
  assert.equal(withdrawn.status, 201);
  const final = (await request(route, tokens.owner)).body;
  assert.equal(final.records.find(row => row.asset.id === fixture.assetId).events[0].sharing.enabled, false);
  assert.equal((await request(route, tokens.office_operator, { ...input, entryKey: 'archived-write', sourceHash: final.sourceHash })).status, 409);
});
