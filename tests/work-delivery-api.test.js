const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { ContractorOperatingLedger } = require('../operating-ledger');
const { WorkBalance } = require('../work-balance');
const { setupDelivery } = require('./work-delivery-contract');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'work-delivery-api-'));
Object.assign(process.env, { STATE_FILE: path.join(directory, 'state.json'), LEDGER_DB_FILE: path.join(directory, 'ledger.sqlite'), UPLOAD_DIR: path.join(directory, 'uploads'), CONTRACTOR_AI_REQUIRE_AUTH: 'true' });
const tokens = { owner: 'work-delivery-owner-token-at-least-32-characters', office_operator: 'work-delivery-office-token-at-least-32-characters', approver: 'work-delivery-approver-token-at-least-32-characters' };
const ledger = new ContractorOperatingLedger({ dbFile: process.env.LEDGER_DB_FILE });
const f = setupDelivery(ledger);
const balance = new WorkBalance(ledger), allocation = balance.command(f.job.id, { action: 'plan', entryKey: randomUUID(), sourceHash: balance.read(f.job.id).sourceHash,
  record: { scopeConfirmed: true, reference: 'Approved production scope for WP-01', reason: 'Allocate the measured baseline to the work package.',
    allocations: [{ lineKey: 'doors', packageId: f.pack.id, plannedQuantity: 2 }] } }, 'balance-office');
ledger.resolveApproval(allocation.approvalId, { status: 'approved', resolvedBy: 'balance-approver' });
ledger.updateOrganizationProfile({ legalName: 'Fixture Contractor', tradingName: 'Fixture Contractor', registrationNumber: '12345678',
  vatNumber: 'NL123456789B01', email: 'finance@example.test', phone: '+31301234567', address: 'Teststraat 1', postalCode: '3511 AA', city: 'Utrecht', country: 'NL', iban: 'NL91 ABNA 0417 1643 00' });
const milestone = ledger.createBillingMilestone(f.job.id, { title: 'First door', amount: 100, taxRate: 21, plannedIssueAt: '2026-09-01', dueAt: '2026-09-30' });
ledger.resolveApproval(milestone.approvalId, { status: 'approved', resolvedBy: 'finance-approver' });
const invoice = ledger.createInvoice(f.job.id, { billingMilestoneId: milestone.id });
ledger.resolveApproval(invoice.approvalId, { status: 'approved', resolvedBy: 'finance-approver' });
ledger.prepareInvoiceIssuePackage(f.job.id, invoice.id);
tokens.field_worker = { token: 'work-delivery-field-token-at-least-32-characters', workerId: f.worker.id };
process.env.CONTRACTOR_AI_ROLE_TOKENS = JSON.stringify(tokens);
const fixture = { jobId: f.job.id, otherId: f.other.id, input: f.input, response: f.response, documentId: f.document.id, milestoneId: milestone.id, invoiceId: invoice.id };
ledger.close();
const app = require('../server');
test('delivery APIs isolate office evidence, approver decisions and assigned field projection', async t => {
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await app.locals.runtimeControl.shutdown({ server, signal: 'work_delivery_api_test' }); assert.ok(path.basename(directory).startsWith('work-delivery-api-')); fs.rmSync(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`, route = `/api/ledger/jobs/${fixture.jobId}/work-deliveries`;
  async function request(route, token, data) {
    const response = await fetch(base + route, { method: data ? 'POST' : 'GET', headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), 'Content-Type': 'application/json' }, ...(data ? { body: JSON.stringify(data) } : {}) });
    return { status: response.status, body: await response.json() };
  }
  assert.equal((await request(route)).status, 401);
  assert.equal((await request(route, tokens.field_worker.token)).status, 403);
  assert.equal((await request(`/api/ledger/documents/${fixture.documentId}/content`, tokens.field_worker.token)).status, 403);
  const read = (await request(route, tokens.approver)).body;
  const input = { action: 'retain', record: fixture.input, sourceHash: read.sourceHash, entryKey: 'api-delivery', actor: 'spoofed' };
  assert.equal((await request(route, tokens.approver, input)).status, 403);
  const created = await request(route, tokens.office_operator, input);
  assert.equal(created.status, 201);
  assert.equal((await request(route, tokens.office_operator, input)).body.replayed, true);
  assert.equal((await request(route, tokens.office_operator, { ...input, entryKey: 'new-stale-key' })).status, 409);
  const current = (await request(route, tokens.owner)).body;
  const response = await request(route, tokens.office_operator, { action: 'request_response', record: fixture.response(created.body.deliveryId), sourceHash: current.sourceHash, entryKey: 'api-response' });
  assert.equal(response.status, 201);
  const approvalRoute = `/api/ledger/approvals/${response.body.approvalId}/resolve?includeDashboard=false`;
  assert.equal((await request(approvalRoute, tokens.office_operator, { status: 'approved' })).status, 403);
  assert.equal((await request(approvalRoute, tokens.approver, { status: 'approved' })).status, 200);
  const retained = (await request(route, tokens.owner)).body.records[0];
  assert.equal(retained.response.status, 'accepted_with_reservations');
  const linkRead = (await request(route, tokens.office_operator)).body;
  const linked = await request(route, tokens.office_operator, { action: 'link', record: { id: created.body.deliveryId, inspectionIds: [], milestoneIds: [fixture.milestoneId] }, sourceHash: linkRead.sourceHash, entryKey: 'api-link-finance' });
  assert.equal(linked.status, 201);
  const closeout = (await request(`/api/ledger/jobs/${fixture.jobId}/closeout-assessment`, tokens.owner)).body.assessment;
  const closeoutPackage = closeout.sections.workPackages.records.find(row => row.code === 'WP-01');
  assert.equal(closeoutPackage.balanceStatus, 'current');
  assert.equal(closeoutPackage.remainingRows[0].remainingQuantity, 1);
  assert.equal(closeoutPackage.deliveries[0].customerResponseStatus, 'accepted_with_reservations');
  assert.deepEqual(closeoutPackage.deliveries[0].invoiceIds, [fixture.invoiceId]);
  assert.equal(closeout.determinations.contractualClosure, 'not_determined');
  const pack = (await request(`/api/ledger/jobs/${fixture.jobId}/work-pack`, tokens.field_worker.token)).body.pack;
  assert.equal(pack.know.workContext.deliveries.length, 1);
  for (const privateText of ['Private customer representative', 'authorityReference', 'receivedAmount']) assert.equal(JSON.stringify(pack).includes(privateText), false);
  const fieldJob = (await request(`/api/ledger/jobs/${fixture.jobId}`, tokens.field_worker.token)).body.job;
  assert.equal(fieldJob.documents.some(document => document.id === fixture.documentId), false);
  assert.equal((await request(`/api/ledger/jobs/${fixture.otherId}/work-pack`, tokens.field_worker.token)).status, 403);
  const exported = (await request('/api/operations/export', tokens.owner)).body;
  assert.equal(exported.workDeliveries.work_deliveries.length, 1);
  const job = (await request(`/api/ledger/jobs/${fixture.jobId}`, tokens.owner)).body.job;
  assert.equal(job.audit.some(event => event.action === 'work_delivery_retain' && event.actor === 'spoofed'), false);
});
