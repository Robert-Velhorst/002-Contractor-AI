const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { ContractorOperatingLedger } = require('../operating-ledger');
const { setup, hierarchy, packageInput } = require('./work-context-contract');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'work-context-api-'));
process.env.STATE_FILE = path.join(directory, 'state.json');
process.env.LEDGER_DB_FILE = path.join(directory, 'ledger.sqlite');
process.env.UPLOAD_DIR = path.join(directory, 'uploads');
process.env.CONTRACTOR_AI_REQUIRE_AUTH = 'true';
const tokens = { owner: 'work-context-owner-token-at-least-32-characters', office_operator: 'work-context-office-token-at-least-32-characters', approver: 'work-context-approver-token-at-least-32-characters' };
const ledger = new ContractorOperatingLedger({ dbFile: process.env.LEDGER_DB_FILE });
const f = setup(ledger), { job, other, worker, command } = f;
const { room } = hierarchy(f); command('save_package', packageInput(f, room.id));
command('save_party', { name: 'Private payer', roles: ['payer'], email: 'payer-private@example.test', shareWithField: false, reference: 'Confirmed' });
tokens.field_worker = { token: 'work-context-field-token-at-least-32-characters', workerId: worker.id };
process.env.CONTRACTOR_AI_ROLE_TOKENS = JSON.stringify(tokens);
ledger.close();
const app = require('../server');

test('work context APIs enforce office edits and prevent field/client contact leaks', async t => {
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await app.locals.runtimeControl.shutdown({ server, signal: 'work_context_api_test' }); assert.ok(path.basename(directory).startsWith('work-context-api-')); fs.rmSync(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  async function request(route, token, data) {
    const response = await fetch(base + route, { method: data ? 'POST' : 'GET', headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), 'Content-Type': 'application/json' }, ...(data ? { body: JSON.stringify(data) } : {}) });
    return { status: response.status, body: await response.json() };
  }
  const route = `/api/ledger/jobs/${job.id}/work-context`;
  assert.equal((await request(route)).status, 401);
  assert.equal((await request(route, tokens.field_worker.token)).status, 403);
  assert.equal((await request('/api/ledger/work-places', tokens.field_worker.token)).status, 403);
  const read = (await request(route, tokens.approver)).body;
  assert.equal(read.parties[0].email, 'payer-private@example.test');
  const input = { action: 'save_place', entryKey: 'api-place', sourceHash: read.sourceHash, record: { type: 'site', name: '<img src=x onerror=alert(1)>' }, actor: 'spoofed' };
  assert.equal((await request(route, tokens.approver, input)).status, 403);
  assert.equal((await request(route, tokens.office_operator, input)).status, 201);
  assert.equal((await request(route, tokens.office_operator, input)).body.replayed, true);
  assert.equal((await request(route, tokens.office_operator, { ...input, entryKey: 'stale' })).status, 409);
  const pack = (await request(`/api/ledger/jobs/${job.id}/work-pack`, tokens.field_worker.token)).body.pack;
  assert.equal(pack.know.workContext.packages.length, 1);
  assert.equal(JSON.stringify(pack).includes('payer-private'), false);
  assert.equal((await request(`/api/ledger/jobs/${other.id}/work-pack`, tokens.field_worker.token)).status, 403);
  const detail = (await request(`/api/ledger/jobs/${job.id}`, tokens.owner)).body.job;
  assert.equal(detail.audit.some(event => event.action === 'save_place' && event.actor === 'spoofed'), false);
  const exported = (await request('/api/operations/export', tokens.owner));
  assert.equal(exported.status, 200);
  assert.equal(exported.body.workContext.work_packages.length, 1);
});
