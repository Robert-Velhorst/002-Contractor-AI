const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { ContractorOperatingLedger } = require('../operating-ledger');
const { setupCoverage } = require('./inspection-coverage-contract');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'inspection-coverage-api-'));
Object.assign(process.env, { CONTRACTOR_AI_DATA_DIR: directory, STATE_FILE: path.join(directory, 'state.json'), LEDGER_DB_FILE: path.join(directory, 'ledger.sqlite'), UPLOAD_DIR: path.join(directory, 'uploads'), CONTRACTOR_AI_REQUIRE_AUTH: 'true' });
const tokens = { owner: 'coverage-owner-token-at-least-32-characters', office_operator: 'coverage-office-token-at-least-32-characters', approver: 'coverage-approver-token-at-least-32-characters' };
const ledger = new ContractorOperatingLedger({ dbFile: process.env.LEDGER_DB_FILE });
const fixture = setupCoverage(ledger);
tokens.field_worker = { token: 'coverage-field-token-at-least-32-characters', workerId: fixture.worker.id };
process.env.CONTRACTOR_AI_ROLE_TOKENS = JSON.stringify(tokens);
ledger.close();
const app = require('../server');
test('coverage API enforces roles, trusted separate reviewers, evidence privacy and retained export', async t => {
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await app.locals.runtimeControl.shutdown({ server, signal: 'inspection_coverage_api_test' }); assert.equal(path.dirname(directory), fs.realpathSync(os.tmpdir())); assert.ok(path.basename(directory).startsWith('inspection-coverage-api-')); fs.rmSync(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`, route = `/api/ledger/jobs/${fixture.job.id}/inspection-coverage`;
  async function request(route, token, data) {
    const response = await fetch(base + route, { method: data ? 'POST' : 'GET', headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), 'Content-Type': 'application/json' }, ...(data ? { body: JSON.stringify(data) } : {}) });
    return { status: response.status, body: await response.json() };
  }
  assert.equal((await request(route)).status, 401);
  assert.equal((await request(route, tokens.field_worker.token)).status, 403);
  assert.equal((await request(`/api/ledger/documents/${fixture.coverageDocument.id}/content`, tokens.field_worker.token)).status, 403);
  const source = (await request(route, tokens.approver)).body;
  const input = { action: 'plan', record: fixture.coveragePlan, entryKey: 'coverage-api-plan', sourceHash: source.sourceHash, actor: 'spoofed' };
  assert.equal((await request(route, tokens.approver, input)).status, 403);
  const created = await request(route, tokens.owner, input);
  assert.equal(created.status, 201, JSON.stringify(created.body));
  assert.equal((await request(route, tokens.owner, input)).body.replayed, true);
  const resolution = `/api/ledger/approvals/${created.body.approvalId}/resolve?includeDashboard=false`;
  assert.equal((await request(resolution, tokens.owner, { status: 'approved', resolvedBy: 'spoofed-other-person' })).status, 409);
  assert.equal((await request(resolution, tokens.approver, { status: 'approved' })).status, 200);
  const refreshed = (await request(route, tokens.owner)).body;
  const assessed = await request(route, tokens.office_operator, { action: 'assessment', record: fixture.coverageAssessment(created.body.decisionId), entryKey: 'coverage-api-assessment', sourceHash: refreshed.sourceHash });
  assert.equal(assessed.status, 201);
  assert.equal((await request(`/api/ledger/approvals/${assessed.body.approvalId}/resolve?includeDashboard=false`, tokens.owner, { status: 'approved' })).status, 200);
  const field = (await request(`/api/ledger/jobs/${fixture.job.id}/work-pack`, tokens.field_worker.token)).body.pack;
  assert.equal(field.know.workContext.deliveries[0].inspectionCoverage.status, 'covered');
  assert.equal(JSON.stringify(field).includes('Private'), false);
  const job = (await request(`/api/ledger/jobs/${fixture.job.id}`, tokens.field_worker.token)).body.job;
  assert.equal(job.documents.some(row => row.id === fixture.coverageDocument.id), false);
  assert.equal((await request(`/api/ledger/jobs/${fixture.other.id}/work-pack`, tokens.field_worker.token)).status, 403);
  const exported = (await request('/api/operations/export', tokens.owner)).body;
  assert.equal(exported.inspectionCoverage.inspection_coverage_decisions.length, 2);
  const audit = (await request(`/api/ledger/jobs/${fixture.job.id}`, tokens.owner)).body.job.audit;
  assert.equal(audit.some(row => row.action === 'request_inspection_coverage_plan' && row.actor === 'spoofed'), false);
});
